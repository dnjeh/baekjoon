#include <stdio.h>
int main() {
    int a[][2] = {{6*60+30, 9*60}, {9*60+50, 10*60}, {10*60+50, 11*60}, {11*60+50, 12*60}, {12*60+50, 13*60+50}, {14*60+40, 14*60+50}, {15*60+40, 15*60+50}, {16*60+40, 22*60+50}};
    int h, m, f=0;
    scanf("%d %d", &h, &m);
    for(int i=0;i<8;i++) {
        if(h*60+m>=a[i][0]&&h*60+m<=a[i][1]) {
            f=1;
            break;
        }
    }
    printf("%s", f?"Yes":"No");
}